// Post-build: gzip the built HTML pages into PROGMEM byte arrays the firmware
// serves with Content-Encoding: gzip.

import { readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))

const PAGES = [
  {
    file: 'index.html',
    header: 'index_page.h',
    symbol: 'indexHtmlPage',
    guard: 'INDEX_PAGE_H',
  },
  {
    file: '404.html',
    header: 'not_found_page.h',
    symbol: 'notFoundHtmlPage',
    guard: 'NOT_FOUND_PAGE_H',
  },
  {
    file: 'update.html',
    header: 'update_page.h',
    symbol: 'updateHtmlPage',
    guard: 'UPDATE_PAGE_H',
  },
]

function toByteArray(buf) {
  const bytes = [...buf].map((b) => '0x' + b.toString(16).padStart(2, '0'))
  const lines = []
  for (let i = 0; i < bytes.length; i += 20) {
    lines.push('  ' + bytes.slice(i, i + 20).join(', '))
  }
  return lines.join(',\n')
}

for (const { file, header, symbol, guard } of PAGES) {
  const html = readFileSync(resolve(here, 'dist', file))
  const gz = gzipSync(html, { level: 9 })

  const out = `// AUTO-GENERATED by web/build-firmware.js - do not edit.
// Source: web/${file === 'index.html' ? 'src' : 'public/' + file} (${html.length} B -> ${gz.length} B gzipped).
#ifndef ${guard}
#define ${guard}

const uint8_t ${symbol}[] PROGMEM = {
${toByteArray(gz)}
};
const unsigned int ${symbol}Len = ${gz.length};

#endif
`

  const target = resolve(here, '../firmware/EspWOL', header)
  writeFileSync(target, out)
  console.log(`  ${header}: ${html.length} B -> ${gz.length} B gz`)
}
