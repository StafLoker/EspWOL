// Post-build: gzip the built HTML pages into PROGMEM byte arrays the firmware
// serves with Content-Encoding: gzip, and minify the captive-portal CSS into a
// PROGMEM string literal.

import { readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))

const PAGES = [
  {
    file: 'index.html',
    header: 'index_page.h',
    symbol: 'INDEX_PAGE_HTML',
    guard: 'INDEX_PAGE_H',
  },
  {
    file: '404.html',
    header: 'not_found_page.h',
    symbol: 'NOT_FOUND_PAGE_HTML',
    guard: 'NOT_FOUND_PAGE_H',
  },
  {
    file: 'update.html',
    header: 'update_page.h',
    symbol: 'UPDATE_PAGE_HTML',
    guard: 'UPDATE_PAGE_H',
  },
]

const PORTAL_CSS = {
  file: 'public/portal.css',
  header: 'wifi_portal_style.h',
  symbol: 'PORTAL_STYLE',
  guard: 'WIFI_PORTAL_STYLE_H',
}

function minifyCss(css) {
  return (
    css
      // Comments. The negative lookahead keeps `/*!` license blocks, of which
      // there are none here, but the habit is cheap.
      .replace(/\/\*(?!!)[\s\S]*?\*\//g, '')
      // Collapse every run of whitespace to a single space.
      .replace(/\s+/g, ' ')
      // Drop the space on both sides of structural punctuation. `:` is left
      // alone because it also appears in pseudo-elements and in values.
      .replace(/\s*([{};,>])\s*/g, '$1')
      // A declaration's `:` is safe to tighten only after a property name,
      // i.e. when it directly follows an identifier inside a block.
      .replace(/([a-z-]+):\s+/g, '$1:')
      // The last declaration before `}` does not need its semicolon.
      .replace(/;}/g, '}')
      // Attribute values that are valid identifiers need no quotes.
      .replace(/\[([a-z-]+)=['"]([a-zA-Z][\w-]*)['"]\]/g, '[$1=$2]')
      .trim()
  )
}

function minifyPageHtml(html) {
  const withMinCss = html.replace(
    /<style>([\s\S]*?)<\/style>/,
    (_, css) => `<style>${minifyCss(css)}</style>`,
  )

  const parts = []
  const scriptRe = /<script\b[^>]*>[\s\S]*?<\/script>/gi
  let last = 0
  for (let m; (m = scriptRe.exec(withMinCss));) {
    parts.push(collapseHtml(withMinCss.slice(last, m.index)), m[0])
    last = m.index + m[0].length
  }
  parts.push(collapseHtml(withMinCss.slice(last)))
  return parts.join('').trim()
}

function collapseHtml(chunk) {
  return chunk
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
}

// Escape for a C string literal, then wrap so no line runs long.
function toCStringLiteral(text, indent = '  ') {
  const escaped = text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')
  const lines = []
  const width = 90
  for (let i = 0; i < escaped.length;) {
    let take = Math.min(width, escaped.length - i)
    // Never split immediately after a backslash, or the escape breaks.
    while (take > 1 && escaped[i + take - 1] === '\\') take--
    lines.push(indent + '"' + escaped.slice(i, i + take) + '"')
    i += take
  }
  return lines.join('\n')
}

function toByteArray(buf) {
  const bytes = [...buf].map((b) => '0x' + b.toString(16).padStart(2, '0'))
  const lines = []
  for (let i = 0; i < bytes.length; i += 20) {
    lines.push('  ' + bytes.slice(i, i + 20).join(', '))
  }
  return lines.join(',\n')
}

for (const { file, header, symbol, guard } of PAGES) {
  const raw = readFileSync(resolve(here, 'dist', file), 'utf8')
  // index.html is already minified by Vite; the public/ pages are not.
  const html = Buffer.from(file === 'index.html' ? raw : minifyPageHtml(raw), 'utf8')
  const gz = gzipSync(html, { level: 9 })

  const out = `// AUTO-GENERATED by web/build-firmware.js - do not edit.
// Source: web/${file === 'index.html' ? 'src' : 'public/' + file} (${html.length} B -> ${gz.length} B gzipped).
#ifndef ${guard}
#define ${guard}

const uint8_t ${symbol}[] PROGMEM = {
${toByteArray(gz)}
};
const unsigned int ${symbol}_LEN = ${gz.length};

#endif
`

  const target = resolve(here, '../firmware/EspWOL', header)
  writeFileSync(target, out)
  console.log(`  ${header}: ${html.length} B -> ${gz.length} B gz`)
}

// Portal CSS -> PROGMEM string literal
{
  const { file, header, symbol, guard } = PORTAL_CSS
  const css = readFileSync(resolve(here, file), 'utf8')
  const min = minifyCss(css)

  const style =
    "<meta name='viewport' content='width=device-width,initial-scale=1'>" +
    "<meta name='theme-color' content='#18181b'>" +
    '<style>' +
    min +
    '</style>'

  const out = `// AUTO-GENERATED by web/build-firmware.js - do not edit.
// Source: web/${file} (${css.length} B -> ${min.length} B minified).
#ifndef ${guard}
#define ${guard}

static const char ${symbol}[] PROGMEM =
${toCStringLiteral(style)};

#endif
`

  writeFileSync(resolve(here, '../firmware/EspWOL', header), out)
  console.log(`  ${header}: ${css.length} B -> ${min.length} B minified`)
}
